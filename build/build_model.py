def merge(builders):
    out = MB()
    for mb in builders:
        off = len(out.verts)
        out.verts.extend(mb.verts)
        for f, m, u in zip(mb.faces, mb.mats, mb.fuv):
            out.faces.append(tuple(i + off for i in f))
            out.mats.append(m)
            out.fuv.append(u)
    return out


