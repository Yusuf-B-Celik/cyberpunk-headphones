# ============================================================ math helpers
def superellipse(n, ry, rz, exp, phase=0.0):
    pts = []
    for k in range(n):
        t = 2.0 * math.pi * k / n + phase
        c, s = math.cos(t), math.sin(t)
        y = ry * math.copysign(abs(c) ** (2.0 / exp), c)
        z = rz * math.copysign(abs(s) ** (2.0 / exp), s)
        pts.append((y, z))
    return pts


def arc_pts_2d(pts, closed):
    """cumulative arc length of a 2D polyline"""
    run = [0.0]
    n = len(pts)
    last = n if closed else n - 1
    for i in range(last):
        a = pts[i]
        b = pts[(i + 1) % n]
        run.append(run[-1] + math.dist(a, b))
    return run


def catmull(p0, p1, p2, p3, t):
    t2, t3 = t * t, t * t * t
    return 0.5 * ((2 * p1) + (-p0 + p2) * t + (2 * p0 - 5 * p1 + 4 * p2 - p3) * t2 + (-p0 + 3 * p1 - 3 * p2 + p3) * t3)


def resample_spline(pts, steps, closed=False):
    """Catmull-Rom through the control points -> smooth path with `steps` samples"""
    out = []
    n = len(pts)
    segs = n if closed else n - 1
    per = max(2, steps // segs)
    for i in range(segs):
        p0 = pts[(i - 1) % n] if closed else pts[max(i - 1, 0)]
        p1 = pts[i]
        p2 = pts[(i + 1) % n] if closed else pts[min(i + 1, n - 1)]
        p3 = pts[(i + 2) % n] if closed else pts[min(i + 2, n - 1)]
        for s in range(per):
            out.append(catmull(p0, p1, p2, p3, s / per))
    if not closed:
        out.append(pts[-1])
    return out


def tube_frames(path, up_hint=Vector((0, 0, 1))):
    """Rotation-minimising frames along a polyline (avoids twisting)."""
    n = len(path)
    tangents = []
    for i in range(n):
        if i == 0:
            t = path[1] - path[0]
        elif i == n - 1:
            t = path[-1] - path[-2]
        else:
            t = path[i + 1] - path[i - 1]
        tangents.append(t.normalized())
    frames = []
    ref = up_hint.normalized()
    if abs(ref.dot(tangents[0])) > 0.95:
        ref = Vector((0, 1, 0))
    nrm = (ref - tangents[0] * ref.dot(tangents[0])).normalized()
    for i, t in enumerate(tangents):
        if i > 0:
            prev_t = tangents[i - 1]
            axis = prev_t.cross(t)
            if axis.length > 1e-9:
                ang = max(-1.0, min(1.0, prev_t.dot(t)))
                nrm = Matrix.Rotation(math.acos(ang), 3, axis.normalized()) @ nrm
            nrm = (nrm - t * nrm.dot(t)).normalized()
        binorm = t.cross(nrm).normalized()
        frames.append((t, nrm, binorm))
    return frames


# ============================================================ mesh builder
class MB:
    """Accumulates verts / faces / per-face materials / per-face-corner UVs."""

    def __init__(self):
        self.verts = []
        self.faces = []
        self.mats = []
        self.fuv = []

    def _v(self, co):
        self.verts.append(tuple(co))
        return len(self.verts) - 1

    def quad(self, a, b, c, d, mat, uv):
        self.faces.append((a, b, c, d))
        self.mats.append(mat)
        self.fuv.append(uv)

    def tri(self, a, b, c, mat, uv):
        self.faces.append((a, b, c))
        self.mats.append(mat)
        self.fuv.append(uv)

    def polygon(self, idx, mat, uvs):
        self.faces.append(tuple(idx))
        self.mats.append(mat)
        self.fuv.append(uvs)

    def to_object(self, name, smooth_angle=32.0):
        if not self.verts:
            raise RuntimeError("empty mesh: " + name)
        me = bpy.data.meshes.new(name)
        me.from_pydata(self.verts, [], self.faces)
        me.validate(verbose=False)
        for m in MAT_ORDER:
            me.materials.append(bpy.data.materials[m])
        for i, poly in enumerate(me.polygons):
            poly.material_index = mat_id(self.mats[i])
            poly.use_smooth = True
        # per-loop UVs
        uv = me.uv_layers.new(name="UVMap")
        for i, poly in enumerate(me.polygons):
            fu = self.fuv[i]
            for c, li in enumerate(poly.loop_indices):
                vi = me.loops[li].vertex_index
                uv.data[li].uv = fu[c]
        ob = bpy.data.objects.new(name, me)
        bpy.context.collection.objects.link(ob)
        # outward-facing normals, sharp edges by angle
        bm = bmesh.new()
        bm.from_mesh(me)
        bmesh.ops.recalc_face_normals(bm, faces=bm.faces)
        bm.to_mesh(me)
        bm.free()
        bpy.context.view_layer.objects.active = ob
        try:
            bpy.ops.object.shade_auto_smooth(angle=math.radians(smooth_angle))
        except Exception:
            bpy.ops.object.shade_smooth()
        return ob


# ==================================================== primitive 1: axial sweep
def sweep_axial(outline, profile, origin, axis, e1, e2,
                u_size=0.06, v_size=0.06, closed_u=True, closed_v=True,
                mod=None, cap_mat="Seam", snap_uv=True):
    """Sweep a closed (a, r) profile around a closed 2D outline.

    outline : [(x, y)] in the e1/e2 plane, physical units, unit loop
    profile : [(axial_offset, radial_scale, mat_of_next_segment)], closed loop
    mod     : optional f(u01, a, r) -> r  (used for panel lines running along u)
    """
    mb = MB()
    nk, nj = len(outline), len(profile)
    r_avg = sum(math.hypot(p[0], p[1]) for p in outline) / nk

    # ---- UV scaling: snap to whole tiles so the loop is seam-free
    u_len = arc_pts_2d(outline, closed_u)[-1]
    v_phys = arc_pts_2d([(a, r * r_avg) for a, r, _ in profile], closed_v)[-1]
    u_tile = max(1.0, round(u_len / u_size)) if snap_uv else u_len / u_size
    v_tile = max(1.0, round(v_phys / v_size)) if snap_uv else v_phys / v_size
    us = arc_pts_2d(outline, closed_u)
    vv = arc_pts_2d([(a, r * r_avg) for a, r, _ in profile], closed_v)
    U = [c / u_len * u_tile for c in us]
    V = [c / v_phys * v_tile for c in vv]

    axis = Vector(axis).normalized()
    e1 = Vector(e1).normalized()
    e2 = Vector(e2).normalized()
    origin = Vector(origin)

    rings = []
    for j, (a, r, _m) in enumerate(profile):
        if abs(r) < 1e-9:
            rings.append([mb._v(origin + axis * a)])          # pole
            continue
        row = []
        for k, op in enumerate(outline):
            rr = r if mod is None else mod(k / nk, a, r)
            row.append(mb._v(origin + axis * a + e1 * (op[0] * rr) + e2 * (op[1] * rr)))
        rings.append(row)

    for j in range(nj):
        if not closed_v and j == nj - 1:
            break
        jn = (j + 1) % nj
        A, B = rings[j], rings[jn]
        mat = profile[j][2]
        va, vb = V[j], V[jn]
        for k in range(nk):
            if not closed_u and k == nk - 1:
                break
            kn = (k + 1) % nk
            uva, uvb = U[k], U[kn]
            if len(A) == 1 and len(B) == 1:
                continue
            if len(A) == 1:
                mb.tri(A[0], B[k], B[kn], mat, [(uva, va), (uva, vb), (uvb, vb)])
            elif len(B) == 1:
                mb.tri(A[k], A[kn], B[0], mat, [(uva, va), (uvb, va), (uva, vb)])
            else:
                mb.quad(A[k], A[kn], B[kn], B[k], mat,
                        [(uva, va), (uvb, va), (uvb, vb), (uva, vb)])

    if not closed_v:  # cap the open ends with fans
        for j, rev in ((0, False), (nj - 1, True)):
            ring = rings[j]
            if len(ring) < 3:
                continue
            cs = Vector((0, 0, 0))
            for k in range(nk):
                cs = cs + Vector(mb.verts[ring[k]])
            cs = cs / nk
            ci = mb._v(cs)
            for k in range(nk):
                kn = (k + 1) % nk
                if rev:
                    mb.tri(ci, ring[kn], ring[k], cap_mat,
                           [(U[k], V[j]), (U[kn], V[j]), (U[k], V[j])])
                else:
                    mb.tri(ci, ring[k], ring[kn], cap_mat,
                           [(U[k], V[j]), (U[kn], V[j]), (U[k], V[j])])
    return mb


# ==================================================== primitive 2: tube sweep
def sweep_tube(path, profile2d, mat, u_size=0.05, v_size=0.05,
               up_hint=Vector((0, 0, 1)), cap=True, cap_mat=None, closed_v=True):
    """Loft a 2D closed cross-section along a 3D path with stable frames."""
    mb = MB()
    frames = tube_frames(path, up_hint)
    r_avg = sum(math.hypot(p[0], p[1]) for p in profile2d) / len(profile2d)
    v_len = arc_pts_2d(profile2d, True)[-1]
    v_tile = max(1.0, round(v_len / v_size))
    vv = [c / v_len * v_tile for c in arc_pts_2d(profile2d, True)]
    # u along the path
    runs = [0.0]
    for i in range(len(path) - 1):
        runs.append(runs[-1] + (path[i + 1] - path[i]).length)
    u_tile = max(1.0, round(runs[-1] / u_size))
    U = [c / runs[-1] * u_tile for c in runs]

    rings = []
    for i, p in enumerate(path):
        _t, nrm, bino = frames[i]
        row = [mb._v(p + nrm * (q[0]) + bino * (q[1])) for q in profile2d]
        rings.append(row)
    nk = len(profile2d)
    for i in range(len(path) - 1):
        A, B = rings[i], rings[i + 1]
        for k in range(nk):
            kn = (k + 1) % nk
            mb.quad(A[k], A[kn], B[kn], B[k], mat,
                    [(U[i], vv[k]), (U[i], vv[kn]), (U[i + 1], vv[kn]), (U[i + 1], vv[k])])
    if cap:
        cm = cap_mat or mat
        for ring, u in ((rings[0], U[0]), (rings[-1], U[-1])):
            cs = Vector((0, 0, 0))
            for k in range(nk):
                cs = cs + Vector(mb.verts[ring[k]])
            ci = mb._v(cs / nk)
            for k in range(nk):
                kn = (k + 1) % nk
                mb.tri(ci, ring[k], ring[kn], cm,
                       [(u, vv[k]), (u, vv[kn]), (u, vv[k])])
    return mb


