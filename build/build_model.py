def mirror_x(ob):
    """Exact mirror of an object across X = 0 (guarantees symmetry)."""
    me = ob.data.copy()
    new_name = ob.name[:-2] + "_L" if ob.name.endswith("_R") else ob.name + "_L"
    me.name = new_name
    nb = bpy.data.objects.new(new_name, me)
    bpy.context.collection.objects.link(nb)
    bm = bmesh.new()
    bm.from_mesh(me)
    for v in bm.verts:
        v.co.x = -v.co.x
    bmesh.ops.recalc_face_normals(bm, faces=bm.faces)
    bm.to_mesh(me)
    bm.free()
    bpy.context.view_layer.objects.active = nb
    try:
        bpy.ops.object.shade_auto_smooth(angle=math.radians(32.0))
    except Exception:
        bpy.ops.object.shade_smooth()
    return nb


