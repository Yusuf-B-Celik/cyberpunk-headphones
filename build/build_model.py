# ================================================================ the parts
def groove(u01, a, r, stations):
    """Flat-bottomed panel groove: returns the radial scale, crisp walls.
    stations: [(u_centre, u_halfwidth, depth)] in normalised outline units."""
    out = r
    for c, hw, d in stations:
        du = abs(((u01 - c + 0.5) % 1.0) - 0.5)
        if du <= hw:
            # trapezoid: 45-degree-ish chamfer over the outer 40% of the groove
            f = 1.0 if du <= hw * 0.6 else (hw - du) / (hw * 0.4)
            out = min(out, r * (1.0 - d * max(0.0, f)))
    return out


