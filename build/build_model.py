def mirror_profile(half):
    """Close a lathe half-profile (y from +tip to the equator) into a full
    symmetric loop; the closing segment between the two poles is degenerate
    and is skipped by sweep_axial."""
    full = list(half)
    for y, r, _m in reversed(half[:-1]):
        full.append((-y, r, ""))
    # every point keeps the material of the segment leaving it
    return [(y, r, m or half[min(i, len(half) - 1)][2]) for i, (y, r, m) in enumerate(full)]


