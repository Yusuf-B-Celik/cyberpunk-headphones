def look_report(paths):
    """Luminance stats per still - a cheap stand-in for eyeballing the render."""
    try:
        import numpy as np
        from PIL import Image
    except Exception as e:  # Blender's bundled python may lack PIL
        return {"skipped": repr(e)}
    out = {}
    for p in paths:
        a = np.asarray(Image.open(p).convert("RGB"), dtype=np.float32) / 255.0
        lum = a.max(axis=2)
        bg = lum < 0.045
        out[os.path.basename(p)] = {
            "p05": round(float(np.percentile(lum, 5)), 3),
            "p50": round(float(np.percentile(lum, 50)), 3),
            "p99": round(float(np.percentile(lum, 99)), 3),
            "clipped_pct": round(float((lum > 0.995).mean() * 100), 2),
            "subject_pct": round(float((~bg).mean() * 100), 1),
            "neon_px": int(((a[:, :, 2] > 0.45) & (a[:, :, 0] < 0.45)).sum()),
        }
    return out


