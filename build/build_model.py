def img(path, non_color=True):
    name = os.path.basename(path)
    im = bpy.data.images.get(name)
    if im is None:
        im = bpy.data.images.load(path)
    im.colorspace_settings.name = "Non-Color" if non_color else "sRGB"
    return im


def set_in(node, names, value):
    for n in names:
        if n in node.inputs:
            node.inputs[n].default_value = value
            return True
    return False


def pbr(name, base_img=None, rough_val=0.5, rough_img=None, norm_img=None,
        norm_strength=1.0, metallic=0.0, base_rgb=(0.5, 0.5, 0.5),
        emission=None, emission_strength=0.0, sheen=0.0, ior=1.5, alpha_img=None):
    mat = bpy.data.materials.get(name) or bpy.data.materials.new(name)
    mat.use_nodes = True
    nt = mat.node_tree
    nt.nodes.clear()
    out = nt.nodes.new("ShaderNodeOutputMaterial")
    out.location = (600, 0)
    bsdf = nt.nodes.new("ShaderNodeBsdfPrincipled")
    bsdf.location = (250, 0)
    nt.links.new(bsdf.outputs["BSDF"], out.inputs["Surface"])
    set_in(bsdf, ["Base Color"], (*base_rgb, 1.0))
    set_in(bsdf, ["Metallic"], metallic)
    set_in(bsdf, ["Roughness"], rough_val)
    set_in(bsdf, ["IOR"], ior)
    if sheen:
        set_in(bsdf, ["Sheen Weight"], sheen)
        set_in(bsdf, ["Sheen Roughness"], 0.35)
    if emission is not None:
        set_in(bsdf, ["Emission Color"], (*emission, 1.0))
        set_in(bsdf, ["Emission Strength"], emission_strength)
    if base_img:
        t = nt.nodes.new("ShaderNodeTexImage")
        t.image = img(os.path.join(TEX, base_img), non_color=False)
        t.location = (-350, 250)
        t.interpolation = "Smart"
        nt.links.new(t.outputs["Color"], bsdf.inputs["Base Color"])
    if rough_img:
        t = nt.nodes.new("ShaderNodeTexImage")
        t.image = img(os.path.join(TEX, rough_img))
        t.location = (-350, -60)
        t.interpolation = "Smart"
        nt.links.new(t.outputs["Color"], bsdf.inputs["Roughness"])
    if alpha_img:
        t = nt.nodes.new("ShaderNodeTexImage")
        t.image = img(os.path.join(TEX, alpha_img))
        t.location = (-350, -330)
        nt.links.new(t.outputs["Color"], bsdf.inputs["Alpha"])
        mat.blend_method = "BLEND"
    if norm_img:
        t = nt.nodes.new("ShaderNodeTexImage")
        t.image = img(os.path.join(TEX, norm_img))
        t.location = (-350, -330)
        nm = nt.nodes.new("ShaderNodeNormalMap")
        nm.location = (-60, -330)
        nm.inputs["Strength"].default_value = norm_strength
        nt.links.new(t.outputs["Color"], nm.inputs["Color"])
        nt.links.new(nm.outputs["Normal"], bsdf.inputs["Normal"])
    return mat


