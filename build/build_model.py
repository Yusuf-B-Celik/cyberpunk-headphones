def fit_camera(cam, direction, target, margin=1.06, only=None):
    """Tight fit: keep every mesh corner inside the frame, computed analytically
    in the camera basis (a bounding sphere would waste half the frame).

    `direction` points from the target towards the camera; `only` restricts the
    fit to object names starting with one of the given prefixes.
    """
    target = Vector(target)
    pts = []
    for o in bpy.data.objects:
        if o.type != "MESH" or o.name.startswith("Floor"):
            continue
        if only and not any(o.name.startswith(p) for p in only):
            continue
        for c in o.bound_box:
            pts.append(o.matrix_world @ Vector(c))

    f = -Vector(direction).normalized()         # camera -> target
    up = Vector((0, 0, 1))
    if abs(f.dot(up)) > 0.95:
        up = Vector((0, 1, 0))
    r = f.cross(up).normalized()
    u = r.cross(f).normalized()
    sensor = cam.data.sensor_width
    th = (sensor / 2) / cam.data.lens
    rx = bpy.context.scene.render.resolution_x
    ry = bpy.context.scene.render.resolution_y
    tv = th * (ry / rx)
    need = 0.0
    for p in pts:
        q = p - target
        a, b, c = q.dot(r), q.dot(u), q.dot(f)
        need = max(need, abs(a) / th - c, abs(b) / tv - c)
    dist = need * margin
    cam.location = target - f * dist
    cam.rotation_euler = f.to_track_quat("-Z", "Y").to_euler()


