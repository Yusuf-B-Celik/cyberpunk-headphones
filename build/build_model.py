def check_symmetry(objs):
    """Verify the left/right halves are exact mirrors (dot-product test)."""
    bad = []
    for o in objs:
        if not o.name.endswith("_R"):
            continue
        l = bpy.data.objects.get(o.name[:-2] + "_L")
        if l is None:
            bad.append(o.name + ": no mirror")
            continue
        a = sorted((round(v.co.x, 5), round(v.co.y, 5), round(v.co.z, 5)) for v in o.data.vertices)
        b = sorted((round(-v.co.x, 5), round(v.co.y, 5), round(v.co.z, 5)) for v in l.data.vertices)
        if a != b:
            diff = sum(1 for x, y in zip(a, b) if x != y)
            bad.append(f"{o.name}: {diff}/{len(a)} verts differ")
    print("SYMMETRY " + json.dumps({"ok": not bad, "problems": bad}))
    return not bad


